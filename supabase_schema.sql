create or replace function save_sale_atomic(
  p_seller_id bigint, p_client_id bigint, p_paid numeric, p_method text,
  p_discount numeric, p_due_date date, p_store_id bigint, p_items jsonb
) returns jsonb language plpgsql security definer set search_path=public as $$
declare
  item jsonb; product_row products%rowtype; variant_row product_variants%rowtype;
  gross numeric := 0; sale_total numeric; new_sale_id bigint; rate numeric := 0;
  qty integer; requested_price numeric; requested_variant bigint; main_store_id bigint; available_stock integer;
begin
  if p_items is null or jsonb_array_length(p_items)=0 then raise exception 'Le ticket est vide.'; end if;
  if coalesce(p_paid,0)<0 then raise exception 'Le montant encaissé ne peut pas être négatif.'; end if;
  select id into main_store_id from stores where name='Boutique principale' limit 1;
  p_store_id := coalesce(p_store_id,main_store_id);
  for item in select * from jsonb_array_elements(p_items) loop
    qty := (item->>'quantity')::integer; requested_price := (item->>'unit_price')::numeric;
    if qty<=0 or requested_price<0 then raise exception 'Ligne de vente invalide.'; end if;
    select * into product_row from products where id=(item->>'product_id')::bigint for update;
    if not found then raise exception 'Produit introuvable %.',item->>'product_id'; end if;
    if p_store_id=main_store_id then available_stock:=product_row.stock;
    else select stock into available_stock from store_stock where store_id=p_store_id and product_id=product_row.id for update; available_stock:=coalesce(available_stock,0); end if;
    if available_stock<qty then raise exception 'Stock insuffisant dans la boutique pour le produit %.',item->>'product_id'; end if;
    requested_variant := nullif(item->>'variant_id','')::bigint;
    if requested_variant is not null then
      select * into variant_row from product_variants where id=requested_variant and product_id=product_row.id and active=true for update;
      if not found or variant_row.stock<qty then raise exception 'Stock insuffisant pour la variante %.',requested_variant; end if;
    end if;
    gross := gross + qty*requested_price;
  end loop;
  p_discount := greatest(0,least(coalesce(p_discount,0),gross)); sale_total := gross-p_discount;
  select coalesce(commission_rate,0) into rate from sellers where id=p_seller_id;
  insert into sales(seller_id,client_id,total,discount,paid,payment_method,due_date,store_id,commission_amount)
  values(p_seller_id,p_client_id,sale_total,p_discount,p_paid,p_method,p_due_date,coalesce(p_store_id,1),sale_total*rate/100)
  returning id into new_sale_id;
  for item in select * from jsonb_array_elements(p_items) loop
    qty := (item->>'quantity')::integer; requested_variant := nullif(item->>'variant_id','')::bigint;
    select * into product_row from products where id=(item->>'product_id')::bigint;
    insert into sale_items(sale_id,product_id,variant_id,quantity,unit_price,unit_cost)
    values(new_sale_id,product_row.id,requested_variant,qty,(item->>'unit_price')::numeric,coalesce(product_row.purchase_price,0));
    if p_store_id=main_store_id then update products set stock=stock-qty where id=product_row.id; end if;
    if requested_variant is not null then update product_variants set stock=stock-qty where id=requested_variant; end if;
    if p_store_id=main_store_id then available_stock:=product_row.stock; else select stock into available_stock from store_stock where store_id=p_store_id and product_id=product_row.id; end if;
    insert into store_stock(store_id,product_id,stock) values(p_store_id,product_row.id,available_stock-qty) on conflict(store_id,product_id) do update set stock=excluded.stock;
  end loop;
  if p_client_id is not null and p_paid>0 then update clients set loyalty_points=loyalty_points+floor(p_paid/1000)::integer where id=p_client_id; end if;
  return jsonb_build_object('sale_id',new_sale_id,'gross',gross,'total',sale_total);
end $$;
revoke all on function save_sale_atomic(bigint,bigint,numeric,text,numeric,date,bigint,jsonb) from public;
grant execute on function save_sale_atomic(bigint,bigint,numeric,text,numeric,date,bigint,jsonb) to service_role;

